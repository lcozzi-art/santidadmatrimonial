def espacios(s):
    """Espacio que no se corta antes de : ; ? ! » y después de « (solo en el texto, no dentro de las etiquetas)."""
    partes = re.split(r"(<[^>]*>)", s)
    return "".join(p if p.startswith("<") else re.sub(r" ([:;?!»])", " \\1", p).replace("« ", "« ") for p in partes)


